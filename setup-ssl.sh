#!/usr/bin/env bash
set -e

GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m'

DOMAIN="lotushut.bluewebspark.com"
EMAIL="contact@bluewebspark.com"

echo -e "${BLUE}======================================================${NC}"
echo -e "${GREEN}   🔒 Setting up Free Let's Encrypt SSL on AWS        ${NC}"
echo -e "${BLUE}======================================================${NC}"

# Check Docker compose command
if docker info &> /dev/null; then
    COMPOSE_CMD="docker compose"
elif sudo docker info &> /dev/null; then
    COMPOSE_CMD="sudo docker compose"
else
    COMPOSE_CMD="docker compose"
fi

# 1. Install certbot
if ! command -v certbot &> /dev/null; then
    echo -e "${YELLOW}Installing certbot...${NC}"
    sudo apt-get update && sudo apt-get install -y certbot
else
    echo -e "${GREEN}✔ Certbot is already installed.${NC}"
fi

# 2. Create placeholder self-signed cert if none exists so Nginx can start
CERT_DIR="/etc/letsencrypt/live/${DOMAIN}"
if [ ! -f "${CERT_DIR}/fullchain.pem" ]; then
    echo -e "${YELLOW}Creating temporary certificate for initial Nginx boot...${NC}"
    sudo mkdir -p "${CERT_DIR}"
    sudo openssl req -x509 -nodes -newkey rsa:2048 -days 1 \
        -keyout "${CERT_DIR}/privkey.pem" \
        -out "${CERT_DIR}/fullchain.pem" \
        -subj "/CN=${DOMAIN}" >/dev/null 2>&1 || true
fi

# 3. Stop Nginx container to free port 80 for Certbot verification
echo -e "${YELLOW}Stopping Nginx container to free port 80 for Let's Encrypt challenge...${NC}"
$COMPOSE_CMD stop nginx 2>/dev/null || true
sudo docker stop restaurant_nginx 2>/dev/null || true

# 4. Request official Let's Encrypt SSL certificate
echo -e "${YELLOW}Requesting official SSL certificate for ${DOMAIN}...${NC}"
if sudo certbot certonly --standalone \
    -d "${DOMAIN}" \
    --agree-tos \
    --email "${EMAIL}" \
    --non-interactive \
    --preferred-challenges http; then
    echo -e "${GREEN}✔ SSL Certificate successfully generated by Let's Encrypt!${NC}"
else
    echo -e "${RED}Certbot challenge encountered an issue. Re-attempting...${NC}"
    sudo certbot certonly --standalone -d "${DOMAIN}" --agree-tos --email "${EMAIL}" --preferred-challenges http
fi

# 5. Fix permissions so Docker container can read the certificates
sudo chmod -R 755 /etc/letsencrypt/live /etc/letsencrypt/archive 2>/dev/null || true

# 6. Start Nginx with SSL enabled
echo -e "${YELLOW}Starting Nginx with SSL on ports 80 & 443...${NC}"
$COMPOSE_CMD up -d nginx

# 7. Setup auto-renewal cronjob (runs daily and reloads nginx)
echo -e "${YELLOW}Configuring automatic renewal cronjob...${NC}"
CRON_JOB="0 3 * * * certbot renew --quiet && docker exec restaurant_nginx nginx -s reload"
(sudo crontab -l 2>/dev/null | grep -Fv "certbot renew"; echo "$CRON_JOB") | sudo crontab -

echo -e "\n${BLUE}======================================================${NC}"
echo -e "${GREEN}   🎉 SSL Setup Completed Successfully!               ${NC}"
echo -e "${BLUE}======================================================${NC}"
echo -e "You can now access your application securely at:"
echo -e "  🔒 Customer Website: ${GREEN}https://${DOMAIN}/${NC}"
echo -e "  ⚙️  Admin Dashboard:  ${GREEN}https://${DOMAIN}/admin/${NC}"
echo -e "  📡 Backend API:      ${GREEN}https://${DOMAIN}/api/health${NC}"
